// Each bank has a world position, three radii, yaw and a density profile.
export function cloudLayout() {
  const banks = [
    [-26,-1.7,8,13,6.7,8.3,-.34,0], [-18,-2.1,15.6,12,6.6,7.2,-.26,3],
    [-32,.3,12,8.8,7.5,7,-.51,2], [-6,.4,-28,16,11,10,.41,2],
    [-19,1,-32,12,15.5,11,-.39,1], [-10,1.3,-36,14,10,11,.47,0],
    [23,-1.15,16.3,10,5.1,6.9,-.8,0], [31,.35,19,12,8.8,9,.4,2],
    [41,1.8,22,13,10.2,9.5,-.3,1], [-38,.2,8,14,7,10,.44,0],
    [-45,1.6,4,11,10.7,10,-.66,1], [-56,2.7,-.5,14,11,10,.56,2],
    [26.1,-1.7,-7.8,8.6,5.6,7.2,.73,3], [37,.8,-13.6,10,9,7.8,.68,2],
  ]
  const distant = [[-88,38,3],[-30,80,4],[76,-68,5],[94,39,3],[-86,-69,4],[-10,-105,3],[143,10,4]]
  let seed = 701
  const random = () => ((seed=(Math.imul(seed,1664525)+1013904223)>>>0)/4294967296)
  for (const [x,z,count] of distant) {
    for (let j=0; j<count; j++) {
      const w = 10+random()*14, form = [2,0,1,3][j%4]
      banks.push([x+(j-1)*8+random()*4,-.8+random()*4,z+(j-1)*4+random()*6,
        w,(form===1?1.03:.56)*w,.73*w,random()*2-.9,form])
    }
  }
  return banks
}
